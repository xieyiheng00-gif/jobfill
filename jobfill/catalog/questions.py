"""Built-in question bank.

Each entry is one *question type*: a canonical wording, the many ways forms
phrase it (aliases and regex patterns), and how to answer it.

Answer strategies
-----------------
fact      read one stored fact                      {"fact": "contact.email"}
template  format several facts                      {"template": "{address.city}, {address.state}"}
derive    plain-Python rule over facts/records      {"derive": "years_with_skill", "args": {...}}
record    one field of a repeating record           {"record": "education", "field": "school"}
ai        written per application by the agent      {"ai": {...}}

Tiers follow the facts they read (see facts.py). Every ``ai`` question is
tier 3: it is never answered from a stored static text. ``mode`` says what the
agent writes from:

unique  fresh answer for this company/application from facts + posting.
        Answers given to OTHER companies are never shown to the model.
adapt   tailor stored base material (STAR stories, summary, strengths)
        to this posting. Still written per application.

``scope`` says when an earlier answer may be reused verbatim:
company       same company asks again (e.g. "why us" on a second role)
application   only inside the same application

Matching (see matcher.py): aliases and patterns run on normalized text
(lowercase, punctuation and apostrophes removed, the application's company
name replaced by ``{company}`` and the role title by ``{role}``). Patterns may
capture named groups that become derive arguments. ``section`` questions
answer fields inside repeating blocks (education/experience/project/reference);
``global_ok`` lets a sectioned question also answer an unsectioned field.
``require``/``exclude`` are keyword guards for pattern and fuzzy matches.
"""

TEXTUAL = ("text", "textarea")
FILE = ("file",)


def fact(key):
    return {"fact": key}


def tpl(template):
    return {"template": template}


def derive(fn, **args):
    return {"derive": fn, "args": args}


def rec(kind, field):
    return {"record": kind, "field": field}


def ai(mode, scope, context, guidance, themes=(), deliverable="text", optional="answer", playbook=None):
    spec = {"mode": mode, "scope": scope, "context": list(context), "guidance": guidance,
            "themes": list(themes), "deliverable": deliverable, "optional": optional}
    if playbook:
        spec["playbook"] = playbook
    return {"ai": spec}


def P(regex, priority=0):
    return {"regex": regex, "priority": priority}


def Q(id, tier, category, text, aliases=(), *, answer, patterns=(), section=None, global_ok=False,
      kinds=None, choices=None, require=(), exclude=()):
    if "ai" in answer and kinds is None:
        kinds = TEXTUAL if answer["ai"]["deliverable"] == "text" else FILE
    return {
        "id": id, "tier": tier, "category": category, "text": text, "aliases": list(aliases),
        "answer": answer, "patterns": [p if isinstance(p, dict) else P(p) for p in patterns],
        "section": section, "global_ok": global_ok, "kinds": list(kinds) if kinds else None,
        "choices": choices, "require": list(require), "exclude": list(exclude),
    }


